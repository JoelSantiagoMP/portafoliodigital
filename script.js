let currentLang = 'en';

function setLanguage(lang) {
    currentLang = lang;
    
    // Update active classes on language toggle buttons
    const langBtnEn = document.querySelector('.lang-en');
    const langBtnEs = document.querySelector('.lang-es');
    
    if (lang === 'en') {
        langBtnEn.classList.add('active');
        langBtnEs.classList.remove('active');
    } else {
        langBtnEs.classList.add('active');
        langBtnEn.classList.remove('active');
    }

    // Translate texts
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Translate placeholders
    document.querySelectorAll('[data-placeholder-i18n]').forEach(element => {
        const key = element.getAttribute('data-placeholder-i18n');
        if (translations[lang][key]) {
            element.setAttribute('placeholder', translations[lang][key]);
        }
    });
}

// Language toggle event listener
document.getElementById('langToggle').addEventListener('click', () => {
    const newLang = currentLang === 'en' ? 'es' : 'en';
    setLanguage(newLang);
});


// ==== Project Filtering System ====
const filterBtns = document.querySelectorAll('.filter-btn');
const projectCards = document.querySelectorAll('.project-card');

filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
        // Remove active class from all buttons
        filterBtns.forEach(b => b.classList.remove('active'));
        // Add active class to clicked button
        btn.classList.add('active');
        
        const filterValue = btn.getAttribute('data-filter');
        
        projectCards.forEach(card => {
            if (filterValue === 'all' || card.getAttribute('data-category') === filterValue) {
                card.style.display = 'flex';
                // Trigger reflow for animation (optional)
                setTimeout(() => {
                    card.style.opacity = '1';
                    card.style.transform = 'translateY(0)';
                }, 50);
            } else {
                card.style.opacity = '0';
                card.style.transform = 'translateY(20px)';
                setTimeout(() => {
                    card.style.display = 'none';
                }, 300); // Wait for transition
            }
        });
        
        // Refresh AOS to prevent weird spacing issues after filtering
        setTimeout(() => {
            AOS.refresh();
        }, 350);
    });
});


// ==== Initialize AOS (Animate On Scroll) ====
document.addEventListener('DOMContentLoaded', () => {
    AOS.init({
        once: true,             
        offset: 80,             
        duration: 900,          
        easing: 'ease-out-cubic'
    });
});

// ==== Mobile Menu Toggle ====
const hamburger = document.querySelector('.hamburger');
const navLinks = document.querySelector('.nav-links');
const navItems = document.querySelectorAll('.nav-links li a');

hamburger.addEventListener('click', () => {
    navLinks.classList.toggle('active');
    const icon = hamburger.querySelector('i');
    
    if (navLinks.classList.contains('active')) {
        icon.classList.remove('fa-bars');
        icon.classList.add('fa-times');
    } else {
        icon.classList.remove('fa-times');
        icon.classList.add('fa-bars');
    }
});

// ==== Close mobile menu on link click ====
navItems.forEach(item => {
    item.addEventListener('click', () => {
        navLinks.classList.remove('active');
        const icon = hamburger.querySelector('i');
        icon.classList.remove('fa-times');
        icon.classList.add('fa-bars');
    });
});

// ==== Navbar Glassmorphism scroll effect ====
const navbar = document.getElementById('navbar');

window.addEventListener('scroll', () => {
    if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
    } else {
        navbar.classList.remove('scrolled');
    }
});
